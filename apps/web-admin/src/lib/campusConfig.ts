export interface FeeHeadConfig {
  id: string;
  label: string;
  percentage: number;
  eligible80C?: boolean;
}

export interface InstallmentFeeHeadAmount {
  id: string;
  label: string;
  amount: number;
  eligible80C?: boolean;
}

export interface CampusConfig {
  logoDataUrl?: string | null;
  stampDataUrl?: string | null;
  signatureDataUrl?: string | null;
  useAutoGeneratedSeal?: boolean;
  stampBlendMode?: boolean;
  receiptPrefix?: string;
  signatoryLabel?: string;
  receiptFooterNote?: string;
  feeHeads: FeeHeadConfig[];
  customSubjects?: string[];
  customClasses?: string[];
  customCircularCategories?: string[];
}

export interface LocalFeeAdjustmentPatch {
  amount?: number;
  concessionAmount?: number;
  concessionReason?: string;
  lateFee?: number;
  feeHeadsJson?: InstallmentFeeHeadAmount[];
  collectedBy?: string;
}

export const DEFAULT_FEE_HEADS: FeeHeadConfig[] = [
  { id: 'tuition', label: 'Tuition Fee', percentage: 65, eligible80C: true },
  { id: 'lab', label: 'Lab & Academic Resources', percentage: 15, eligible80C: false },
  { id: 'activity', label: 'Smart Campus & Activity', percentage: 12, eligible80C: false },
  { id: 'development', label: 'Development & Maintenance', percentage: 8, eligible80C: false },
];

export function buildDefaultCampusConfig(schoolCode = 'SCH-01', session = '2026-27'): CampusConfig {
  return {
    logoDataUrl: null,
    stampDataUrl: null,
    signatureDataUrl: null,
    useAutoGeneratedSeal: true,
    stampBlendMode: true,
    receiptPrefix: `${schoolCode}/${session}/`,
    signatoryLabel: 'Authorized Signatory / Accounts Officer',
    receiptFooterNote: 'Fees once paid are non-transferable. Valid for Income Tax Sec. 80C on Tuition component.',
    feeHeads: DEFAULT_FEE_HEADS.map((h) => ({ ...h })),
    customSubjects: [],
    customClasses: [],
    customCircularCategories: [],
  };
}

export function normalizeCampusConfig(
  raw: any,
  schoolCode = 'SCH-01',
  session = '2026-27'
): CampusConfig {
  const defaults = buildDefaultCampusConfig(schoolCode, session);
  if (!raw || typeof raw !== 'object') return defaults;

  const parsedHeads =
    Array.isArray(raw.feeHeads) && raw.feeHeads.length > 0
      ? raw.feeHeads
          .map((h: any, idx: number) => ({
            id: String(h.id || `head-${idx + 1}`),
            label: String(h.label || `Fee Head ${idx + 1}`).trim(),
            percentage: Number(h.percentage || 0),
            eligible80C: Boolean(h.eligible80C),
          }))
          .filter((h: FeeHeadConfig) => h.label.length > 0)
      : defaults.feeHeads;

  return {
    logoDataUrl: typeof raw.logoDataUrl === 'string' ? raw.logoDataUrl : null,
    stampDataUrl: typeof raw.stampDataUrl === 'string' ? raw.stampDataUrl : null,
    signatureDataUrl: typeof raw.signatureDataUrl === 'string' ? raw.signatureDataUrl : null,
    useAutoGeneratedSeal:
      typeof raw.useAutoGeneratedSeal === 'boolean' ? raw.useAutoGeneratedSeal : true,
    stampBlendMode: typeof raw.stampBlendMode === 'boolean' ? raw.stampBlendMode : true,
    receiptPrefix:
      typeof raw.receiptPrefix === 'string' ? raw.receiptPrefix : defaults.receiptPrefix,
    signatoryLabel:
      typeof raw.signatoryLabel === 'string' && raw.signatoryLabel.trim()
        ? raw.signatoryLabel
        : defaults.signatoryLabel,
    receiptFooterNote:
      typeof raw.receiptFooterNote === 'string' && raw.receiptFooterNote.trim()
        ? raw.receiptFooterNote
        : defaults.receiptFooterNote,
    feeHeads: parsedHeads.length > 0 ? parsedHeads : defaults.feeHeads,
    customSubjects: Array.isArray(raw.customSubjects) ? raw.customSubjects : [],
    customClasses: Array.isArray(raw.customClasses) ? raw.customClasses : [],
    customCircularCategories: Array.isArray(raw.customCircularCategories)
      ? raw.customCircularCategories
      : [],
  };
}

export function loadLocalCampusConfig(schoolCode = 'SCH-01', session = '2026-27'): CampusConfig {
  if (typeof window === 'undefined') return buildDefaultCampusConfig(schoolCode, session);
  try {
    const raw = window.localStorage.getItem(`edzy_campus_config_${schoolCode}`);
    if (!raw) return buildDefaultCampusConfig(schoolCode, session);
    return normalizeCampusConfig(JSON.parse(raw), schoolCode, session);
  } catch {
    return buildDefaultCampusConfig(schoolCode, session);
  }
}

export function saveLocalCampusConfig(schoolCode: string, config: CampusConfig): void {
  if (typeof window === 'undefined') return;
  try {
    window.localStorage.setItem(`edzy_campus_config_${schoolCode}`, JSON.stringify(config));
  } catch {
    // Ignore storage quota errors
  }
}

export function loadLocalFeeAdjustments(
  schoolCode: string
): Record<string, LocalFeeAdjustmentPatch> {
  if (typeof window === 'undefined') return {};
  try {
    const raw = window.localStorage.getItem(`edzy_fee_adjustments_${schoolCode}`);
    return raw ? (JSON.parse(raw) as Record<string, LocalFeeAdjustmentPatch>) : {};
  } catch {
    return {};
  }
}

export function saveLocalFeeAdjustment(
  schoolCode: string,
  installmentId: string,
  patch: LocalFeeAdjustmentPatch
): void {
  if (typeof window === 'undefined') return;
  try {
    const current = loadLocalFeeAdjustments(schoolCode);
    current[installmentId] = { ...current[installmentId], ...patch };
    window.localStorage.setItem(`edzy_fee_adjustments_${schoolCode}`, JSON.stringify(current));
  } catch {
    // Ignore storage errors
  }
}

/** Distributes grossAmount cleanly across configured percentage feeHeads so the sum equals grossAmount to the exact rupee. */
export function computeHeadAmountsFromTotal(
  grossAmount: number,
  feeHeads: FeeHeadConfig[]
): InstallmentFeeHeadAmount[] {
  const safeHeads = feeHeads.length > 0 ? feeHeads : DEFAULT_FEE_HEADS;
  const totalPct = safeHeads.reduce((sum, h) => sum + Math.max(0, h.percentage), 0) || 100;
  const safeGross = Math.max(0, Math.round(grossAmount));

  let allocated = 0;
  return safeHeads.map((head, idx) => {
    const isLast = idx === safeHeads.length - 1;
    const amt = isLast
      ? Math.max(0, safeGross - allocated)
      : Math.round((safeGross * Math.max(0, head.percentage)) / totalPct);
    allocated += amt;
    return {
      id: head.id,
      label: head.label,
      amount: amt,
      eligible80C: Boolean(head.eligible80C),
    };
  });
}
